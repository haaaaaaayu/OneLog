def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out = {}
    for amount, names in SIZES:
        for name in names:
            if name in out:
                continue  # 먼저 지정한 크기를 유지한다
            unit = "장" if name == "월계수잎" else "g"
            label = f"{name.replace('-', ' ')} {amount}{unit}"
            entry = {"amount": amount, "unit": unit, "label": label}
            grams = UNIT_GRAMS.get(name)
            if grams:
                # 판매 단위 자체의 단위도 환산표에 넣어야 서로 변환된다.
                # g를 항상 기준으로 둔다. 판매 단위가 g가 아니어도 서로 환산된다.
                entry["unitGrams"] = {"g": 1.0, **{k: float(v) for k, v in grams.items()}}
            out[name] = entry

    path = os.path.join(here, "sale_units.json")
    json.dump({"note": "마트 일반 소포장 기준 대표값. 사용자 확인값이 아니며 앱에서 덮어쓸 수 있다.", "saleUnits": out},
              open(path, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"대표 판매 단위 {len(out)}종 → {path}")


if __name__ == "__main__":
    main()
